/**
 * The systemd units of `caelo-agent` (#696 Phase 4c), as text. Pure, so the
 * exact files are unit-tested; agent/systemd.ts installs them.
 *
 * Why a systemd --user timer on the host, and not a container: the agent
 * has to run `docker compose` for the install, and the only way a container
 * could is the Docker socket — root on the host for anything that gets into
 * that container (Watchtower, the usual answer, was archived in 2025 and
 * verifies no signatures). The agent instead runs as the operator who ran
 * `init`, a member of the `docker` group like that operator already is to
 * run Compose at all; nothing new gets Docker access, and no unit runs as
 * root.
 *
 * Shape: a oneshot service (one poll: heartbeat, then claim and run at most
 * one request) started by a timer every {@link PLATFORM_UPDATE_AGENT_POLL_SECONDS}
 * seconds after the previous run ended — systemd never starts the service
 * while a run (an upgrade can take many minutes) is still active.
 *
 * The service runs the provisioning CLI pinned to an exact release
 * (`bun x --bun @caelo-cms/provisioning@<version> agent run`); a successful
 * update re-pins it to the release it installed.
 */

import { createHash } from "node:crypto";
import { PLATFORM_UPDATE_AGENT_POLL_SECONDS } from "@caelo-cms/shared";

/** Everything the units name; all paths absolute. */
export interface AgentUnitSpec {
  /** Unit base name (`caelo-agent-<domain>-<hash>`), see {@link agentUnitName}. */
  readonly name: string;
  readonly domain: string;
  /** The provisioning release the service runs. */
  readonly version: string;
  /** The `bun` binary (the one that ran `init`). */
  readonly bunPath: string;
  /** The install's `.caelo/` directory. */
  readonly caeloDir: string;
  /** Where `.caelo/` lives (the service's working directory). */
  readonly workDir: string;
  /** PATH for the service: docker, cosign and bun must be on it. */
  readonly path: string;
  /** DOCKER_HOST of the installing shell (rootless Docker), when set. */
  readonly dockerHost?: string;
  /**
   * The provenance-verified CLI of {@link version} (agent/cli-provenance.ts)
   * — what an update re-pins the agent to. Without it the service runs the
   * release the operator installed with (`bun x`, as they did by hand).
   */
  readonly cliPath?: string;
}

/** The longest a single run (one full upgrade) may take before systemd stops it. */
export const AGENT_RUN_TIMEOUT_MINUTES = 80;

/**
 * `caelo-agent-<domain>-<hash>`: one agent per install, several installs
 * per host possible. The slug is for people; the hash of the install's
 * `.caelo/` path keeps two installs apart even when their slugs collide
 * (`a.b.example.com` vs `a-b.example.com`).
 */
export function agentUnitName(domain: string, caeloDir: string): string {
  const slug = domain
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
  if (!slug) throw new Error(`cannot name the agent unit after domain ${JSON.stringify(domain)}`);
  const hash = createHash("sha256").update(caeloDir).digest("hex").slice(0, 8);
  return `caelo-agent-${slug}-${hash}`;
}

/** The package the service runs, pinned. */
export function agentPackageRef(version: string): string {
  if (!/^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$/.test(version)) {
    throw new Error(`not a release version: ${JSON.stringify(version)}`);
  }
  return `@caelo-cms/provisioning@${version}`;
}

/**
 * One systemd word: double-quoted, `%` escaped (systemd specifiers). Values
 * with a quote, backslash or control character are refused rather than
 * escaped — they are paths and versions, and such a path is a mistake.
 */
function word(value: string): string {
  if (!value || /["\\\p{Cc}]/u.test(value)) {
    throw new Error(`cannot put ${JSON.stringify(value)} into a systemd unit`);
  }
  return `"${value.replace(/%/g, "%%")}"`;
}

/** `Environment="KEY=value"`. */
function environment(key: string, value: string): string {
  return `Environment=${word(`${key}=${value}`)}`;
}

/** The argv of one agent run (also what `agent status` shows). */
export function agentRunArgv(
  spec: Pick<AgentUnitSpec, "bunPath" | "version" | "cliPath">,
): string[] {
  if (spec.cliPath) return [spec.bunPath, spec.cliPath, "agent", "run"];
  return [spec.bunPath, "x", "--bun", agentPackageRef(spec.version), "agent", "run"];
}

/** `<name>.service`. */
export function agentServiceUnit(spec: AgentUnitSpec): string {
  return [
    "# SPDX-License-Identifier: MPL-2.0",
    "# Generated by cms-provision (agent install) — do not edit; re-run it instead.",
    "[Unit]",
    `Description=Caelo update agent for ${spec.domain}`,
    "Documentation=https://caelo-cms.com/docs/install/maintenance/",
    "After=network-online.target",
    "",
    "[Service]",
    "Type=oneshot",
    `WorkingDirectory=${word(spec.workDir)}`,
    environment("CAELO_SELF_HOSTED_DIR", spec.caeloDir),
    environment("PATH", spec.path),
    ...(spec.dockerHost ? [environment("DOCKER_HOST", spec.dockerHost)] : []),
    `ExecStart=${agentRunArgv(spec).map(word).join(" ")}`,
    `TimeoutStartSec=${AGENT_RUN_TIMEOUT_MINUTES}min`,
    // Backups, config.json and the lock file: the operator's only.
    "UMask=0077",
    "NoNewPrivileges=yes",
    "Nice=5",
    "",
  ].join("\n");
}

/** `<name>.timer`. */
export function agentTimerUnit(spec: Pick<AgentUnitSpec, "name" | "domain">): string {
  return [
    "# SPDX-License-Identifier: MPL-2.0",
    "# Generated by cms-provision (agent install) — do not edit; re-run it instead.",
    "[Unit]",
    `Description=Poll for Caelo updates for ${spec.domain}`,
    "",
    "[Timer]",
    // The first poll a minute after the timer starts (install, boot);
    // then a minute after each run ends.
    "OnActiveSec=1min",
    "OnBootSec=2min",
    `OnUnitInactiveSec=${PLATFORM_UPDATE_AGENT_POLL_SECONDS}s`,
    "AccuracySec=5s",
    `Unit=${spec.name}.service`,
    "",
    "[Install]",
    "WantedBy=timers.target",
    "",
  ].join("\n");
}

/** The release an installed service file runs, or null when it names none. */
export function pinnedAgentVersion(serviceUnit: string): string | null {
  const exec = /^ExecStart=.*$/m.exec(serviceUnit)?.[0] ?? "";
  const m =
    /@caelo-cms\/provisioning@([0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?)"/.exec(exec) ??
    /\/caelo-([0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?)\/node_modules\//.exec(exec);
  return m?.[1] ?? null;
}
