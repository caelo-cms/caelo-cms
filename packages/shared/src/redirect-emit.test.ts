/**
 * #587 — the per-provider emitters of the redirect plan: Caddy snippet,
 * GCP URL-map path rules, CloudFront KeyValueStore + function, Front Door
 * rules. (The Caddy snippet also runs through a real Caddy in
 * packages/provisioning/src/caddy-redirects.docker.test.ts.)
 */

import { describe, expect, it } from "bun:test";
import { caddyRedirectsImport, emitCaddyRedirects } from "./redirect-emit-caddy.js";
import {
  CLOUDFRONT_KVS_MAX_KEY_BYTES,
  CloudFrontKvsLimitError,
  cloudFrontKeyValueEntries,
  cloudFrontRedirectFunctionCode,
} from "./redirect-emit-cloudfront.js";
import {
  FRONT_DOOR_MAX_RULES,
  FrontDoorRuleLimitError,
  frontDoorRedirectRules,
} from "./redirect-emit-front-door.js";
import {
  assertGcpRedirectBudget,
  GCP_PUBLIC_BASE_PATHS,
  GcpUrlMapBudgetError,
  gcpRedirectPathRules,
  withGcpRedirects,
} from "./redirect-emit-gcp.js";
import { buildRedirectPlan, type RedirectPlan, type RedirectTableRow } from "./redirect-plan.js";

const planOf = (rows: RedirectTableRow[]): RedirectPlan =>
  buildRedirectPlan({ rows, pageUrlStyle: "directory", servedFiles: new Set() });
const row = (fromPath: string, toPath: string, statusCode = 301): RedirectTableRow => ({
  fromPath,
  toPath,
  statusCode,
});
const PLAN = planOf([
  row("/old", "/new"),
  row("/promo.html", "/sale", 302),
  row("/q", "/t?a=1", 308),
  row("/gone", "/410", 410),
]);
const EMPTY = planOf([]);

describe("emitCaddyRedirects", () => {
  it("maps every match path to target + status and redirects per status", () => {
    expect(emitCaddyRedirects(PLAN)).toBe(
      [
        "# Auto-generated by Caelo static-generator from the redirects table. Do not edit.",
        "map {path} {caelo_redirect_to} {caelo_redirect_status} {",
        "\t/old /new/{?query} 301",
        "\t/old/ /new/{?query} 301",
        "\t/promo.html /sale/{?query} 302",
        "\t/q /t?a=1 308",
        "\t/q/ /t?a=1 308",
        "\t/gone - 410",
        "\t/gone/ - 410",
        "}",
        "@caelo_redirect_301 vars {caelo_redirect_status} 301",
        "redir @caelo_redirect_301 {caelo_redirect_to} 301",
        "@caelo_redirect_302 vars {caelo_redirect_status} 302",
        "redir @caelo_redirect_302 {caelo_redirect_to} 302",
        "@caelo_redirect_308 vars {caelo_redirect_status} 308",
        "redir @caelo_redirect_308 {caelo_redirect_to} 308",
        "@caelo_gone vars {caelo_redirect_status} 410",
        "handle @caelo_gone {",
        "\trespond 410",
        "}",
        "",
      ].join("\n"),
    );
  });

  it("emits only the header for an empty plan (a valid empty import)", () => {
    expect(emitCaddyRedirects(EMPTY)).toBe(
      "# Auto-generated by Caelo static-generator from the redirects table. Do not edit.\n",
    );
  });

  it("refuses characters a Caddyfile token cannot carry", () => {
    expect(() => emitCaddyRedirects(planOf([row("/a{b}", "/c")]))).toThrow(/'\{' is '%7B'/);
    expect(() => emitCaddyRedirects(planOf([row("/a", '/c"d')]))).toThrow(/Caddyfile/);
  });

  it("imports the snippet with a wildcard so a site root without a build still starts", () => {
    expect(caddyRedirectsImport("/srv/caelo/output/production/current/")).toBe(
      "import /srv/caelo/output/production/current/_redirects.caddy*",
    );
  });
});

describe("GCP URL-map rules", () => {
  it("emits one urlRedirect path rule per redirect, keeping the query", () => {
    const plan = planOf([
      row("/old", "/new"),
      row("/promo.html", "/sale", 302),
      row("/x", "/y", 307),
    ]);
    expect(gcpRedirectPathRules(plan)).toEqual([
      {
        paths: ["/old", "/old/"],
        urlRedirect: {
          pathRedirect: "/new/",
          redirectResponseCode: "MOVED_PERMANENTLY_DEFAULT",
          stripQuery: false,
        },
      },
      {
        paths: ["/promo.html"],
        urlRedirect: { pathRedirect: "/sale/", redirectResponseCode: "FOUND", stripQuery: false },
      },
      {
        paths: ["/x", "/x/"],
        urlRedirect: {
          pathRedirect: "/y/",
          redirectResponseCode: "TEMPORARY_REDIRECT",
          stripQuery: false,
        },
      },
    ]);
  });

  it("refuses what a URL map cannot express", () => {
    expect(() => gcpRedirectPathRules(planOf([row("/a*", "/b")]))).toThrow(/wildcard/);
    expect(() => gcpRedirectPathRules(planOf([row("/a", "/b?x=1")]))).toThrow(/query string/);
  });

  it("replaces earlier redirect rules and keeps the stack's routing first", () => {
    const api = { paths: ["/api/*"], service: "gateway" };
    const stale = { paths: ["/stale"], urlRedirect: { pathRedirect: "/x/" } };
    const out = withGcpRedirects(
      { name: "public", defaultService: "bucket", pathRules: [api, stale] },
      planOf([row("/old", "/new")]),
    );
    expect(out.defaultService).toBe("bucket");
    expect(out.pathRules?.map((r) => r.paths)).toEqual([["/api/*"], ["/old", "/old/"]]);
  });

  it("an empty plan removes every redirect rule", () => {
    const out = withGcpRedirects(
      {
        name: "public",
        pathRules: [
          { paths: ["/api/*"], service: "g" },
          { paths: ["/a"], urlRedirect: {} },
        ],
      },
      EMPTY,
    );
    expect(out.pathRules).toEqual([{ paths: ["/api/*"], service: "g" }]);
  });

  it("refuses a plan over the 1,000-predicate quota with the counts, before any change", () => {
    const base = [{ paths: [...GCP_PUBLIC_BASE_PATHS] }];
    const rows = (n: number) => Array.from({ length: n }, (_, i) => row(`/p${i}`, "/x"));
    expect(() => assertGcpRedirectBudget(planOf(rows(499)), base)).not.toThrow();
    try {
      assertGcpRedirectBudget(planOf(rows(500)), base);
      throw new Error("expected GcpUrlMapBudgetError");
    } catch (e) {
      expect(e).toBeInstanceOf(GcpUrlMapBudgetError);
      expect((e as GcpUrlMapBudgetError).predicatesNeeded).toBe(1001);
      expect((e as Error).message).toContain("500 redirect(s) need 1001 paths");
      expect((e as Error).message).toContain("bulk_delete_redirects");
    }
    // File-like paths cost one predicate each.
    const files = Array.from({ length: 999 }, (_, i) => row(`/p${i}.html`, "/x"));
    expect(() => assertGcpRedirectBudget(planOf(files), base)).not.toThrow();
  });

  it("refuses a path matcher using routeRules (changed outside the stack)", () => {
    expect(() => withGcpRedirects({ name: "public", routeRules: [{}] }, EMPTY)).toThrow(
      /routeRules/,
    );
  });
});

describe("CloudFront KeyValueStore + function", () => {
  it("stores one entry per match path, sorted", () => {
    expect(cloudFrontKeyValueEntries(PLAN)).toEqual([
      { key: "/gone", value: '{"s":410}' },
      { key: "/gone/", value: '{"s":410}' },
      { key: "/old", value: '{"s":301,"l":"/new/","q":1}' },
      { key: "/old/", value: '{"s":301,"l":"/new/","q":1}' },
      { key: "/promo.html", value: '{"s":302,"l":"/sale/","q":1}' },
      { key: "/q", value: '{"s":308,"l":"/t?a=1"}' },
      { key: "/q/", value: '{"s":308,"l":"/t?a=1"}' },
    ]);
  });

  it("refuses a plan over the store limits", () => {
    const long = `/${"a".repeat(CLOUDFRONT_KVS_MAX_KEY_BYTES)}`;
    expect(() => cloudFrontKeyValueEntries(planOf([row(long, "/x")]))).toThrow(
      CloudFrontKvsLimitError,
    );
    const many = Array.from({ length: 30_000 }, (_, i) =>
      row(`/${String(i).padStart(60, "0")}`, `/${"t".repeat(60)}`),
    );
    expect(() => cloudFrontKeyValueEntries(planOf(many))).toThrow(/a store holds 5242880/);
  });

  it("the function answers stored paths and passes the rest through", async () => {
    const entries = new Map(cloudFrontKeyValueEntries(PLAN).map((e) => [e.key, e.value]));
    const kvsIds: string[] = [];
    const cf = {
      kvs(id: string) {
        kvsIds.push(id);
        return {
          async get(key: string, opts: { format: string }) {
            expect(opts.format).toBe("json");
            const v = entries.get(key);
            if (v === undefined) throw new Error(`The key ${key} does not exist`);
            return JSON.parse(v);
          },
        };
      },
    };
    const code = cloudFrontRedirectFunctionCode("abc-123");
    expect(code.startsWith("import cf from 'cloudfront';")).toBe(true);
    const handler = new Function(
      "cf",
      `${code.replace("import cf from 'cloudfront';", "")}\nreturn handler;`,
    )(cf) as (e: unknown) => Promise<Record<string, unknown>>;
    expect(kvsIds).toEqual(["abc-123"]);
    const req = (uri: string, query = "") => ({
      request: { uri, rawQueryString: () => query },
    });

    expect(await handler(req("/old/", "utm=x&y=1"))).toEqual({
      statusCode: 301,
      statusDescription: "Moved Permanently",
      headers: { location: { value: "/new/?utm=x&y=1" } },
    });
    expect(await handler(req("/q", "dropped=1"))).toEqual({
      statusCode: 308,
      statusDescription: "Permanent Redirect",
      headers: { location: { value: "/t?a=1" } },
    });
    expect(await handler(req("/promo.html"))).toMatchObject({
      statusCode: 302,
      headers: { location: { value: "/sale/" } },
    });
    expect(await handler(req("/gone"))).toEqual({ statusCode: 410, statusDescription: "Gone" });
    const passthrough = req("/live/");
    expect(await handler(passthrough)).toBe(passthrough.request);
  });

  it("refuses something that is not a store id in the generated code", () => {
    expect(() => cloudFrontRedirectFunctionCode("x'); evil('")).toThrow(/not a KeyValueStore id/);
  });
});

describe("Front Door rules", () => {
  it("emits one UrlPath + UrlRedirect rule per redirect", () => {
    const rules = frontDoorRedirectRules(PLAN);
    expect(rules.map((r) => [r.ruleName, r.order])).toEqual([
      ["caeloRedirect1", 1],
      ["caeloRedirect2", 2],
      ["caeloRedirect3", 3],
    ]);
    expect(rules[0]?.conditions[0].parameters.matchValues).toEqual(["old", "old/"]);
    expect(rules[0]?.actions[0].parameters).toEqual({
      typeName: "DeliveryRuleUrlRedirectActionParameters",
      redirectType: "Moved",
      destinationProtocol: "MatchRequest",
      customPath: "/new/",
    });
    expect(rules[1]?.actions[0].parameters.redirectType).toBe("Found");
    expect(rules[2]?.actions[0].parameters).toMatchObject({
      redirectType: "PermanentRedirect",
      customPath: "/t",
      customQueryString: "a=1",
    });
  });

  it("replaces the visitor's query for a fragment-only target", () => {
    const [rule] = frontDoorRedirectRules(planOf([row("/a", "/b#top")]));
    expect(rule?.actions[0].parameters).toMatchObject({
      customPath: "/b",
      customQueryString: "",
      customFragment: "top",
    });
  });

  it("refuses more redirects than a route holds", () => {
    const rows = Array.from({ length: FRONT_DOOR_MAX_RULES + 1 }, (_, i) => row(`/p${i}`, "/x"));
    expect(() => frontDoorRedirectRules(planOf(rows))).toThrow(FrontDoorRuleLimitError);
  });
});
