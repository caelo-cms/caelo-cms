/**
 * The redirect plan as a Caddyfile snippet (self-hosted, #587).
 *
 * The static generator writes it to `<build>/_redirects.caddy`; each public
 * Caddy site block imports the file of the build it serves, and the deploy
 * reloads Caddy through its admin API (static-publisher-self-hosted.ts), so
 * a redirect is answered by Caddy itself with no compute on the request
 * path. A reload re-reads imports; a bad snippet is rejected by Caddy, which
 * keeps the previous config, and the deploy reports the error.
 *
 * Shape: one `map` from the request path to the target and status, then one
 * `redir` per status keyed on the mapped status. `map` is an exact,
 * case-sensitive string lookup — unlike Caddy's `path` matcher, which is
 * case-insensitive and would let `/About` shadow a live `/about`. One map
 * keeps the config O(1) in directives however many rows the table holds.
 * `redir` sorts before `try_files` / `file_server` / `handle`, so the
 * directive order inside the site block does not matter.
 */

import type { RedirectPlan } from "./redirect-plan.js";
import { trimTrailingSlashes } from "./url.js";

/** The file name the generator writes the snippet to, at the build root. */
export const CADDY_REDIRECTS_FILE = "_redirects.caddy";

/**
 * The `import` line for a site block serving `siteRoot`. The trailing `*`
 * (Caddy's import globs allow exactly one) lets a site root without a build
 * yet — fresh install, nothing published — import nothing instead of failing
 * Caddy's start; Caddy only errors on a missing import without a wildcard.
 * Every build the generator writes carries the file.
 */
export function caddyRedirectsImport(siteRoot: string): string {
  return `import ${trimTrailingSlashes(siteRoot)}/${CADDY_REDIRECTS_FILE}*`;
}

/**
 * Self-hosted: Caddy's admin API listens on this unix socket, in a volume
 * only Caddy and the admin mount (never the gateway, which handles public
 * traffic). The admin reloads Caddy through it after every deploy so the
 * imported redirect snippet takes effect.
 */
export const CADDY_ADMIN_SOCKET_DIR = "/run/caddy-admin";
export const CADDY_ADMIN_SOCKET = `${CADDY_ADMIN_SOCKET_DIR}/admin.sock`;
/** Admin env: the socket above. */
export const CADDY_ADMIN_SOCKET_ENV = "CAELO_CADDY_ADMIN_SOCKET";
/** Admin env: a read-only copy of the Caddyfile Caddy runs, for the reload. */
export const CADDYFILE_ENV = "CAELO_CADDYFILE";

const PLACEHOLDER_TARGET = "caelo_redirect_to";
const PLACEHOLDER_STATUS = "caelo_redirect_status";

/**
 * Characters a Caddyfile token cannot carry literally: `{`/`}` start a
 * placeholder, quotes and backticks delimit tokens. Stored paths are
 * percent-encoded URLs, so these never occur in practice; a row that has
 * them fails the build rather than becoming a different rule.
 */
const CADDY_UNSAFE = /[{}"`\\]/;

/**
 * Render the plan as a Caddyfile snippet for a site block.
 *
 * @example
 *   emitCaddyRedirects({ redirects: [{ fromPath: "/old", matchPaths: ["/old", "/old/"],
 *     location: "/new/", statusCode: 301, preserveQuery: true }], gone: [], shadowedByBuild: [] })
 *   // map {path} {caelo_redirect_to} {caelo_redirect_status} {
 *   //   /old /new/{?query} 301
 *   //   /old/ /new/{?query} 301
 *   // }
 *   // @caelo_redirect_301 vars {caelo_redirect_status} 301
 *   // redir @caelo_redirect_301 {caelo_redirect_to} 301
 */
export function emitCaddyRedirects(plan: RedirectPlan): string {
  const lines = [
    "# Auto-generated by Caelo static-generator from the redirects table. Do not edit.",
  ];
  if (plan.redirects.length === 0 && plan.gone.length === 0) return `${lines[0]}\n`;

  lines.push(`map {path} {${PLACEHOLDER_TARGET}} {${PLACEHOLDER_STATUS}} {`);
  for (const r of plan.redirects) {
    assertCaddySafe(r.fromPath, r.location);
    const target = r.preserveQuery ? `${r.location}{?query}` : r.location;
    for (const path of r.matchPaths) lines.push(`\t${path} ${target} ${r.statusCode}`);
  }
  for (const g of plan.gone) {
    assertCaddySafe(g.fromPath, "");
    for (const path of g.matchPaths) lines.push(`\t${path} - 410`);
  }
  lines.push("}");

  const statuses = [...new Set(plan.redirects.map((r) => r.statusCode))].sort();
  for (const status of statuses) {
    lines.push(`@caelo_redirect_${status} vars {${PLACEHOLDER_STATUS}} ${status}`);
    lines.push(`redir @caelo_redirect_${status} {${PLACEHOLDER_TARGET}} ${status}`);
  }
  if (plan.gone.length > 0) {
    // `handle` (not a bare `respond`): `respond` sorts after `handle`, so a
    // catch-all `handle { file_server }` in the site block would win.
    lines.push(`@caelo_gone vars {${PLACEHOLDER_STATUS}} 410`);
    lines.push("handle @caelo_gone {", "\trespond 410", "}");
  }
  return `${lines.join("\n")}\n`;
}

function assertCaddySafe(fromPath: string, location: string): void {
  for (const value of [fromPath, location]) {
    if (CADDY_UNSAFE.test(value)) {
      throw new Error(
        `redirect-emit-caddy: the redirect for ${JSON.stringify(fromPath)} contains one of { } " \` \\ in ${JSON.stringify(value)}, which a Caddyfile cannot carry literally. Percent-encode the character in the stored path (e.g. '{' is '%7B') with bulk_create_redirects (upsert), then rebuild.`,
      );
    }
  }
}
