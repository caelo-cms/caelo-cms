/**
 * The redirect plan for CloudFront (provider `aws`, #587).
 *
 * CloudFront has no static redirect rules; the edge-native way is a
 * CloudFront Function on viewer-request reading a CloudFront KeyValueStore.
 * The function is a sub-millisecond lookup that runs at the edge before the
 * S3 origin (no Lambda, no origin round-trip), and the store is updated by
 * the deploy without republishing the function. S3 website routing rules are
 * not an option: they are capped at 50 and need the website endpoint, while
 * the stack serves S3 through an origin access identity.
 *
 * One key per request path the plan answers (`/old`, `/old/`), value a small
 * JSON document. Store limits (CloudFront quotas, fixed): 5 MB per store,
 * keys up to 512 bytes, values up to 1 KB. A plan that does not fit is
 * refused with {@link CloudFrontKvsLimitError}; nothing is written.
 */

import type { RedirectPlan } from "./redirect-plan.js";

/** CloudFront KeyValueStore limits. */
export const CLOUDFRONT_KVS_MAX_TOTAL_BYTES = 5 * 1024 * 1024;
export const CLOUDFRONT_KVS_MAX_KEY_BYTES = 512;
export const CLOUDFRONT_KVS_MAX_VALUE_BYTES = 1024;

/** One KeyValueStore entry. */
export interface CloudFrontKvsEntry {
  readonly key: string;
  readonly value: string;
}

/**
 * The value stored per path: `s` status, `l` Location, `q` 1 when the
 * visitor's query string is appended. A 410 entry carries only `s`.
 */
export interface CloudFrontRedirectValue {
  readonly s: number;
  readonly l?: string;
  readonly q?: 1;
}

/** The plan does not fit a CloudFront KeyValueStore; nothing was written. */
export class CloudFrontKvsLimitError extends Error {
  constructor(detail: string) {
    super(
      `redirect-emit-cloudfront: ${detail} Nothing was published and the live redirects are unchanged. Delete redirects nobody links to any more (find_redirects lists them, bulk_delete_redirects removes them), then publish again.`,
    );
    this.name = "CloudFrontKvsLimitError";
  }
}

const utf8Length = (s: string): number => new TextEncoder().encode(s).length;

/**
 * The KeyValueStore entries for a plan, sorted by key.
 *
 * @throws {CloudFrontKvsLimitError} when a key, a value or the whole set is
 *         over the store's limits.
 */
export function cloudFrontKeyValueEntries(plan: RedirectPlan): CloudFrontKvsEntry[] {
  const entries: CloudFrontKvsEntry[] = [];
  for (const r of plan.redirects) {
    const value: CloudFrontRedirectValue = {
      s: r.statusCode,
      l: r.location,
      ...(r.preserveQuery ? { q: 1 as const } : {}),
    };
    for (const key of r.matchPaths) entries.push({ key, value: JSON.stringify(value) });
  }
  for (const g of plan.gone) {
    for (const key of g.matchPaths) entries.push({ key, value: JSON.stringify({ s: 410 }) });
  }
  entries.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));

  let total = 0;
  for (const e of entries) {
    if (utf8Length(e.key) > CLOUDFRONT_KVS_MAX_KEY_BYTES) {
      throw new CloudFrontKvsLimitError(
        `the redirect path ${JSON.stringify(e.key)} is longer than the ${CLOUDFRONT_KVS_MAX_KEY_BYTES}-byte key limit.`,
      );
    }
    if (utf8Length(e.value) > CLOUDFRONT_KVS_MAX_VALUE_BYTES) {
      throw new CloudFrontKvsLimitError(
        `the redirect target for ${JSON.stringify(e.key)} is longer than the ${CLOUDFRONT_KVS_MAX_VALUE_BYTES}-byte value limit.`,
      );
    }
    total += utf8Length(e.key) + utf8Length(e.value);
  }
  if (total > CLOUDFRONT_KVS_MAX_TOTAL_BYTES) {
    throw new CloudFrontKvsLimitError(
      `the ${entries.length} redirect path(s) need ${total} bytes; a store holds ${CLOUDFRONT_KVS_MAX_TOTAL_BYTES}.`,
    );
  }
  return entries;
}

/**
 * Source of the viewer-request CloudFront Function (runtime
 * `cloudfront-js-2.0`) that answers the store's entries. A path without an
 * entry passes through to the origin unchanged.
 *
 * @param kvsId The KeyValueStore's id (the last segment of its ARN).
 */
export function cloudFrontRedirectFunctionCode(kvsId: string): string {
  if (!/^[A-Za-z0-9-]+$/.test(kvsId)) {
    throw new Error(`redirect-emit-cloudfront: ${JSON.stringify(kvsId)} is not a KeyValueStore id`);
  }
  return `import cf from 'cloudfront';

// Generated by @caelo-cms/shared (redirect-emit-cloudfront.ts). Answers the
// redirects table from the KeyValueStore the deploy writes (#587).
const kvs = cf.kvs('${kvsId}');
const REASON = {
  301: 'Moved Permanently',
  302: 'Found',
  307: 'Temporary Redirect',
  308: 'Permanent Redirect',
};

async function handler(event) {
  const request = event.request;
  let hit;
  try {
    hit = await kvs.get(request.uri, { format: 'json' });
  } catch (e) {
    // kvs.get throws for a key that is not in the store: no redirect.
    return request;
  }
  if (hit.s === 410) {
    return { statusCode: 410, statusDescription: 'Gone' };
  }
  let location = hit.l;
  if (hit.q === 1) {
    const query = request.rawQueryString();
    if (query) location += '?' + query;
  }
  return {
    statusCode: hit.s,
    statusDescription: REASON[hit.s],
    headers: { location: { value: location } },
  };
}
`;
}
