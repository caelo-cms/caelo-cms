/** Every schema.org type a node may have, by its exact name. */
export const SCHEMA_ORG_TYPES: ReadonlySet<string> = new Set([
  ...CREATIVE_WORKS,
  ...EVENTS,
  ...ORGANIZATIONS,
  ...LOCAL_BUSINESSES,
  ...PLACES,
  ...PRODUCTS,
  ...INTANGIBLES,
]);

/** Whether `name` is a schema.org type core lets a node have. */
export function isSchemaOrgType(name: string): boolean {
  return SCHEMA_ORG_TYPES.has(name);
}
